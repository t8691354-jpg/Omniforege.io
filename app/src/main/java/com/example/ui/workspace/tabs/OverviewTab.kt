@Composable
fun OverviewTab(
    project: Project,
    tasks: List<DevelopmentTask>,
    files: List<ProjectFile>,
    checkpoints: List<Checkpoint>,
    isGenerating: Boolean,
    onRunPlan: () -> Unit,
    onManualCheckpoint: () -> Unit,
    onNavigateToBuild: () -> Unit,
    onNavigateToKeys: () -> Unit
) {
    val completedCount = tasks.count { it.status == TaskStatus.COMPLETED.name }
    val totalCount = tasks.size.coerceAtLeast(1)
    val progress = (completedCount.toFloat() / totalCount).coerceIn(0f, 1f)
    val latestCheckpoint = checkpoints.firstOrNull()

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(16.dp)
    ) {
        // Project Header Card
        Card(
            modifier = Modifier.fillMaxWidth(),
            colors = CardDefaults.cardColors(containerColor = Color(0xFF1E293B)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(modifier = Modifier.padding(18.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text(
                            text = project.name,
                            style = MaterialTheme.typography.titleLarge.copy(
                                fontWeight = FontWeight.Bold,
                                color = Color(0xFFF1F5F9)
                            )
                        )
                        Text(
                            text = "${project.targetPlatform} • ${project.language} / ${project.framework}",
                            style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF38BDF8))
                        )
                    }

                    StatusBadge(status = project.status)
                }

                Spacer(modifier = Modifier.height(14.dp))

                Text(
                    text = project.description.ifBlank { "Autonomous software project generated by OmniForge AI." },
                    style = MaterialTheme.typography.bodyMedium.copy(color = Color(0xFF94A3B8))
                )

                Spacer(modifier = Modifier.height(16.dp))

                // Progress Bar
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text(
                        text = "Build Pipeline Progress",
                        style = MaterialTheme.typography.labelMedium.copy(color = Color(0xFFCBD5E1))
                    )
                    Text(
                        text = "$completedCount / ${tasks.size} tasks (${(progress * 100).toInt()}%)",
                        style = MaterialTheme.typography.labelMedium.copy(
                            fontWeight = FontWeight.Bold,
                            color = Color(0xFF38BDF8)
                        )
                    )
                }
                Spacer(modifier = Modifier.height(8.dp))
                LinearProgressIndicator(
                    progress = { progress },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(8.dp)
                        .clip(RoundedCornerShape(4.dp)),
                    color = Color(0xFF0284C7),
                    trackColor = Color(0xFF0F172A)
                )
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Key Metrics Row
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            MetricCard(
                modifier = Modifier.weight(1f),
                icon = Icons.Default.CheckCircle,
                title = "Tasks Done",
                value = "$completedCount/${tasks.size}",
                tint = Color(0xFF10B981)
            )
            MetricCard(
                modifier = Modifier.weight(1f),
                icon = Icons.Default.Folder,
                title = "Files Created",
                value = "${files.size}",
                tint = Color(0xFF38BDF8)
            )
            MetricCard(
                modifier = Modifier.weight(1f),
                icon = Icons.Default.Bookmark,
                title = "Checkpoints",
                value = "${checkpoints.size}",
                tint = Color(0xFFF59E0B)
            )
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Active Provider & Failover Safeguard Card
        Card(
            modifier = Modifier.fillMaxWidth(),
            colors = CardDefaults.cardColors(containerColor = Color(0xFF1E293B)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(modifier = Modifier.padding(18.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.AutoAwesome,
                        contentDescription = null,
                        tint = Color(0xFFF59E0B),
                        modifier = Modifier.size(22.dp)
                    )
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "Active AI Provider & Continuity",
                        style = MaterialTheme.typography.titleMedium.copy(
                            fontWeight = FontWeight.Bold,
                            color = Color(0xFFF1F5F9)
                        )
                    )
                }

                Spacer(modifier = Modifier.height(10.dp))

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Text(
                            text = "Assigned Provider: ${project.activeProvider}",
                            style = MaterialTheme.typography.bodyMedium.copy(
                                fontWeight = FontWeight.SemiBold,
                                color = Color(0xFF38BDF8)
                            )
                        )
                        Text(
                            text = "Model: ${project.activeModel}",
                            style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF94A3B8))
                        )
                    }

                    OutlinedButton(
                        onClick = onNavigateToKeys,
                        shape = RoundedCornerShape(8.dp),
                        colors = ButtonDefaults.outlinedButtonColors(contentColor = Color(0xFF38BDF8))
                    ) {
                        Text("Manage Keys")
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                Text(
                    text = "If this provider exhausts quota, OmniForge will automatically freeze state, preserve all ${files.size} source files, and allow you to continue with another key without rework.",
                    style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF64748B))
                )
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Latest Checkpoint Snapshot Card
        if (latestCheckpoint != null) {
            Card(
                modifier = Modifier.fillMaxWidth(),
                colors = CardDefaults.cardColors(containerColor = Color(0xFF0F172A)),
                shape = RoundedCornerShape(16.dp)
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Default.CloudDone,
                            contentDescription = null,
                            tint = Color(0xFF10B981),
                            modifier = Modifier.size(20.dp)
                        )
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(
                            text = "Latest Checkpoint (v${latestCheckpoint.version})",
                            style = MaterialTheme.typography.titleSmall.copy(
                                fontWeight = FontWeight.Bold,
                                color = Color(0xFFF1F5F9)
                            )
                        )
                    }
                    Spacer(modifier = Modifier.height(6.dp))
                    Text(
                        text = latestCheckpoint.title,
                        style = MaterialTheme.typography.bodyMedium.copy(
                            fontWeight = FontWeight.SemiBold,
                            color = Color(0xFFE2E8F0)
                        )
                    )
                    Text(
                        text = latestCheckpoint.contextSummary,
                        style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF94A3B8)),
                        maxLines = 2
                    )
                }
            }
            Spacer(modifier = Modifier.height(16.dp))
        }

        // Action Buttons
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            Button(
                onClick = onRunPlan,
                enabled = !isGenerating && completedCount < tasks.size,
                shape = RoundedCornerShape(10.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = Color(0xFF0284C7),
                    contentColor = Color.White
                ),
                modifier = Modifier
                    .weight(1f)
                    .height(50.dp)
                    .testTag("run_plan_button")
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(imageVector = Icons.Default.PlayArrow, contentDescription = null)
                    Spacer(modifier = Modifier.width(6.dp))
                    Text(
                        text = if (isGenerating) "Building..." else "Run Plan",
                        fontWeight = FontWeight.Bold
                    )
                }
            }

            OutlinedButton(
                onClick = onManualCheckpoint,
                shape = RoundedCornerShape(10.dp),
                colors = ButtonDefaults.outlinedButtonColors(contentColor = Color(0xFFF59E0B)),
                modifier = Modifier
                    .weight(1f)
                    .height(50.dp)
                    .testTag("save_checkpoint_button")
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(imageVector = Icons.Default.Bookmark, contentDescription = null)
                    Spacer(modifier = Modifier.width(6.dp))
                    Text("Save Snapshot")
                }
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Autonomous Telemetry & Resource Card
        Card(
            modifier = Modifier.fillMaxWidth(),
            colors = CardDefaults.cardColors(containerColor = Color(0xFF1E293B)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(modifier = Modifier.padding(18.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.Build,
                        contentDescription = null,
                        tint = Color(0xFF38BDF8),
                        modifier = Modifier.size(20.dp)
                    )
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "Autonomous Telemetry & Resource Limits",
                        style = MaterialTheme.typography.titleMedium.copy(
                            fontWeight = FontWeight.Bold,
                            color = Color(0xFFF1F5F9)
                        )
                    )
                }

                Spacer(modifier = Modifier.height(12.dp))

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text("Tokens Tracked", style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF94A3B8)))
                        Text(
                            text = "${com.example.data.ai.MultiProviderEngine.totalEstimatedTokens} tokens",
                            style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.Bold, color = Color(0xFFF1F5F9))
                        )
                    }
                    Column(modifier = Modifier.weight(1f)) {
                        Text("Requests Handled", style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF94A3B8)))
                        Text(
                            text = "${com.example.data.ai.MultiProviderEngine.totalRequestsHandled} calls",
                            style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.Bold, color = Color(0xFF10B981))
                        )
                    }
                    Column(modifier = Modifier.weight(1f)) {
                        Text("Circuit Breakers", style = MaterialTheme.typography.bodySmall.copy(color = Color(0xFF94A3B8)))
                        Text(
                            text = "Healthy (0 Tripped)",
                            style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.Bold, color = Color(0xFF38BDF8))
                        )
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(10.dp))

        Button(
            onClick = onNavigateToBuild,
            shape = RoundedCornerShape(10.dp),
            colors = ButtonDefaults.buttonColors(
                containerColor = Color(0xFF334155),
                contentColor = Color(0xFFF1F5F9)
            ),
            modifier = Modifier
                .fillMaxWidth()
                .height(48.dp)
                .testTag("open_build_button")
        ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(imageVector = Icons.Default.Build, contentDescription = null)
                Spacer(modifier = Modifier.width(8.dp))
                Text("Build Sandbox & Package ZIP")
            }
        }
    }
}

@Composable
private fun StatusBadge(status: String) {
    val (bgColor, textColor, label) = when (status) {
        ProjectStatus.RUNNING.name -> Triple(Color(0xFF0369A1).copy(alpha = 0.3f), Color(0xFF38BDF8), "Building")
        ProjectStatus.PLANNING.name -> Triple(Color(0xFF7E22CE).copy(alpha = 0.3f), Color(0xFFA855F7), "Planning")
        ProjectStatus.TESTING.name -> Triple(Color(0xFF0E7490).copy(alpha = 0.3f), Color(0xFF06B6D4), "Verifying")
        ProjectStatus.RECOVERING.name -> Triple(Color(0xFFC2410C).copy(alpha = 0.3f), Color(0xFFF97316), "Recovering")
        ProjectStatus.COMPLETED.name -> Triple(Color(0xFF065F46).copy(alpha = 0.3f), Color(0xFF34D399), "Completed")
        ProjectStatus.PAUSED_QUOTA.name -> Triple(Color(0xFF7F1D1D).copy(alpha = 0.4f), Color(0xFFF87171), "Paused (Quota)")
        ProjectStatus.CANCELLED.name -> Triple(Color(0xFF374151).copy(alpha = 0.4f), Color(0xFF9CA3AF), "Cancelled")
        ProjectStatus.READY.name -> Triple(Color(0xFF1E293B), Color(0xFFF59E0B), "Ready")
        else -> Triple(Color(0xFF1E293B), Color(0xFF94A3B8), status)
    }

    Box(
        modifier = Modifier
            .clip(RoundedCornerShape(8.dp))
            .background(bgColor)
            .padding(horizontal = 10.dp, vertical = 5.dp)
    ) {
        Text(
            text = label,
            style = MaterialTheme.typography.labelSmall.copy(
                fontWeight = FontWeight.Bold,
                color = textColor
            )
        )
    }
}

@Composable
private fun MetricCard(
    modifier: Modifier = Modifier,
    icon: ImageVector,
    title: String,
    value: String,
    tint: Color
) {
    Card(
        modifier = modifier,
        colors = CardDefaults.cardColors(containerColor = Color(0xFF1E293B)),
        shape = RoundedCornerShape(12.dp)
    ) {
        Column(
            modifier = Modifier.padding(12.dp),
            verticalArrangement = Arrangement.Center
        ) {
            Icon(
                imageVector = icon,
                contentDescription = null,
                tint = tint,
                modifier = Modifier.size(20.dp)
            )
            Spacer(modifier = Modifier.height(6.dp))
            Text(
                text = value,
                style = MaterialTheme.typography.titleMedium.copy(
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFFF1F5F9)
                )
            )
            Text(
                text = title,
                style = MaterialTheme.typography.bodySmall.copy(
                    color = Color(0xFF94A3B8),
                    fontSize = 11.sp
                )
            )
        }
    }
}
